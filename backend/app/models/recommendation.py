"""
Recommendation Database Model.
Stores actionable, prioritized security advice across modules
(Document Scanner, Exposure Monitor, Breach Monitor).
"""
from datetime import datetime, timezone
import uuid
from sqlalchemy.dialects.postgresql import UUID
from backend.app import db


class Recommendation(db.Model):
    """
    Actionable remediation recommendation generated by security assessment modules.
    """
    __tablename__ = "recommendations"

    id = db.Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id = db.Column(UUID(as_uuid=True), db.ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    document_id = db.Column(UUID(as_uuid=True), db.ForeignKey("documents.id", ondelete="SET NULL"), nullable=True, index=True)
    exposure_record_id = db.Column(UUID(as_uuid=True), db.ForeignKey("exposure_records.id", ondelete="SET NULL"), nullable=True, index=True)
    breach_result_id = db.Column(UUID(as_uuid=True), db.ForeignKey("breach_results.id", ondelete="SET NULL"), nullable=True, index=True)
    
    source_module = db.Column(db.String(50), nullable=False)  # breach_monitor, exposure_monitor, document_scanner
    category = db.Column(db.String(50), nullable=False)       # credential, financial, identity, security_posture
    priority = db.Column(db.String(20), nullable=False)       # LOW, MEDIUM, HIGH, CRITICAL
    title = db.Column(db.String(200), nullable=False)
    description = db.Column(db.Text, nullable=False)
    action_type = db.Column(db.String(50), nullable=False)   # change_password, enable_mfa, freeze_card, etc.
    is_dismissed = db.Column(db.Boolean, nullable=False, default=False)
    created_at = db.Column(db.DateTime(timezone=True), nullable=False, default=lambda: datetime.now(timezone.utc))

    __table_args__ = (
        db.Index("idx_recommendations_user_active", "user_id", "is_dismissed", created_at.desc()),
    )

    # Relationships
    user = db.relationship("User", backref=db.backref("recommendations", lazy="dynamic", cascade="all, delete-orphan"))
    breach_result = db.relationship("BreachResult", back_populates="recommendations")

    def to_dict(self) -> dict:
        return {
            "id": str(self.id),
            "document_id": str(self.document_id) if self.document_id else None,
            "exposure_record_id": str(self.exposure_record_id) if self.exposure_record_id else None,
            "breach_result_id": str(self.breach_result_id) if self.breach_result_id else None,
            "source_module": self.source_module,
            "category": self.category,
            "priority": self.priority,
            "title": self.title,
            "description": self.description,
            "action_type": self.action_type,
            "is_dismissed": self.is_dismissed,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }
